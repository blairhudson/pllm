    def test_07_accounting_ignores_only_timing_value_width(self):
        import msgpack
        import numpy as np
        from pllm.runtime.stage_protocol import MaskedStageResponse, PreparedStageBatchResponse

        def packet(clock=65535, *, columns=32, bits=16, identifier="0" * 32):
            return PreparedStageBatchResponse(identifier, np.zeros((33, columns), dtype=np.uint32), bits, clock).pack()

        first, second = packet(), packet(65536)
        left = FRAMING["account_response"](first, stage_id="public-fixed-stage")
        right = FRAMING["account_response"](second, stage_id="public-fixed-stage")
        FRAMING["assert_equal_static_contract"]([left], [right])
        self.assertEqual(right["full_frame_bytes"] - left["full_frame_bytes"], 2)
        self.assertEqual(left["static_contract"]["arithmetic_payload_bytes"], 33 * 32 * 2)
        controls = []
        for label, value in (("geometry", packet(columns=33)), ("wire-width", packet(bits=24))):
            different = FRAMING["account_response"](value, stage_id="public-fixed-stage")
            with self.assertRaises(AssertionError):
                FRAMING["assert_equal_static_contract"]([left], [different])
            controls.append({"case": label, "outcome": "rejected", "accounting": different})
        masked = [MaskedStageResponse("0" * size, np.zeros((33, 32), dtype=np.uint32), 1 << 16, 16,
                                      65535, "public-fixed-stage").pack() for size in (32, 33)]
        masked_accounts = [FRAMING["account_response"](value, stage_id="public-fixed-stage") for value in masked]
        with self.assertRaises(AssertionError):
            FRAMING["assert_equal_static_contract"]([masked_accounts[0]], [masked_accounts[1]])
        controls.append({"case": "non-timing-metadata-length", "outcome": "rejected", "accounting": masked_accounts})
        truncated = msgpack.unpackb(first[12:], raw=False)
        truncated[-1] = truncated[-1][:-1]
        with self.assertRaises(ValueError):
            FRAMING["account_response"](first[:12] + msgpack.packb(truncated, use_bin_type=True), stage_id="public-fixed-stage")
        (OUTPUT / "framing-65535.bin").write_bytes(first)
        (OUTPUT / "framing-65536.bin").write_bytes(second)
        save(OUTPUT / "framing-controls.json", {"left": left, "right": right, "negative_controls": controls,
                                                "truncated_arithmetic_payload": "rejected",
                                                "historical_failure": "unresolved; original frames absent"})

    def uvicorn_shutdown(self, signum):
        from pllm.runtime.servers import _spawn_role_process

        outcomes = []
        for captured in (False, True):
            directory = OUTPUT / f"uvicorn-{signum.name}-{'captured' if captured else 'control'}"
            directory.mkdir()
            argv = [sys.executable, "-I", str(OUTPUT / "no-model-uvicorn.py"), str(directory)]
            with (directory / "service.log").open("w") as stream:
                if captured:
                    process = _spawn_role_process(argv, environment=POLICY["clean_environment"](os.environ),
                                                  stdout=stream, stderr=subprocess.STDOUT)
                else:
                    process = POLICY["_POPEN"](argv, env=POLICY["clean_environment"](os.environ),
                                                stdout=stream, stderr=subprocess.STDOUT, start_new_session=True)
                self.addCleanup(stop_owned_group, process)
                wait_file(directory / "ready.json", process)
                ready = json.loads((directory / "ready.json").read_text())
                deadline = time.monotonic() + 5
                while True:
                    try:
                        with urllib.request.urlopen(f"http://127.0.0.1:{ready['port']}/identity", timeout=1) as response:
                            self.assertEqual(response.status, 200)
                            served = json.load(response)
                        break
                    except urllib.error.URLError:
                        if process.poll() is not None or time.monotonic() > deadline:
                            raise
                        time.sleep(0.01)
                expected = json.loads((OUTPUT / "provenance.json").read_text())
                self.assertEqual(served["native_sha256"], expected["native_sha256"])
                self.assertEqual(served["pid"], process.pid)
                os.killpg(process.pid, signum)
                returncode = process.wait(timeout=5)
                self.assertTrue((directory / "shutdown.json").is_file())
                self.assertTrue(group_absent(process.pid))
                item = {"argv": argv, "captured": captured, "returncode": returncode,
                        "signal": int(signum), "http_status": 200, "served_identity": served,
                        "lifespan_shutdown": True, "process_group_absent": True}
                save(directory / "outcome.json", item)
                outcomes.append(item)
                if captured:
                    endings = [json.loads(path.read_text()) for path in (OUTPUT / "child-identities").glob("*.end.json")]
                    ending = next(record for record in endings if record["pid"] == process.pid)
                    self.assertEqual(ending["status"], "passed")
                    self.assertEqual(ending["native_sha256"], expected["native_sha256"])
                    self.assertEqual(ending["wheel_package_files"], expected["wheel_package_files"])
                    self.assertEqual(ending["process_group"], process.pid)
                    if signum == signal.SIGTERM:
                        self.assertEqual(ending["termination"], {"kind": "default-signal", "signal": int(signum),
                                                               "original_handler": "SIG_DFL"})
        self.assertEqual(outcomes[0]["returncode"], outcomes[1]["returncode"])
        if signum == signal.SIGTERM:
            self.assertEqual(outcomes[0]["returncode"], -signal.SIGTERM)

