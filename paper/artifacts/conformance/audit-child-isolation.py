def save(path, value):
    POLICY["save"](path, value)


def stop_owned_group(process):
    """Only audit-owned, new-session children; never signal the controller group."""
    assert process.pid != os.getpgrp()
    if process.poll() is None:
        try:
            os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        try:
            process.wait(timeout=3)
        except subprocess.TimeoutExpired:
            pass
    # A group can outlive its leader. Retire the owned group, then reap the child.
    try:
        os.killpg(process.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    process.wait(timeout=3)


def wait_file(path, process, timeout=8):
    deadline = time.monotonic() + timeout
    while not path.is_file():
        if process.poll() is not None or time.monotonic() > deadline:
            raise RuntimeError(f"child did not reach ready point: {path.name}")
        time.sleep(0.01)


def group_absent(pid):
    try:
        os.killpg(pid, 0)
    except ProcessLookupError:
        return True
    return False


def raw_command(argv, environment, name, *, cwd=None):
    process = POLICY["_POPEN"](argv, env=environment, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                                start_new_session=True)
    try:
        stdout, stderr = process.communicate(timeout=30)
    finally:
        stop_owned_group(process)
    (OUTPUT / f"{name}.stdout.txt").write_text(stdout)
    (OUTPUT / f"{name}.stderr.txt").write_text(stderr)
    save(OUTPUT / f"{name}.command.json", {"argv": argv, "exit_code": process.returncode,
                                         "scope": "non-provider subprocess probe"})
    return process.returncode, stdout, stderr


