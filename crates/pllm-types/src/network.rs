/// Output retains request fields; placement_digest commits to all other fields.
#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
pub struct ValidatedNetworkPlacement {
    #[serde(flatten)]
    pub request: NetworkPlacementRequest,
    pub schedule_digest: Digest,
    pub model_plan_digest: Digest,
    pub composition_digest: Digest,
    /// Per-role owned tensor elements at one byte each, deduplicated by native
    /// artifact ID across both phases. Excludes scales, float source storage,
    /// native copies, working buffers and peak memory.
    pub minimum_weight_bytes: BTreeMap<String, u64>,
    /// Owned-weight resident lower bound only; currently equals weight floor.
    pub minimum_memory_bytes: BTreeMap<String, u64>,
    pub placement_digest: Digest,
}

fn nonzero_digest<'de, D: Deserializer<'de>>(deserializer: D) -> Result<Digest, D::Error> {
    let digest = Digest::deserialize(deserializer)?;
    if digest.as_str().bytes().all(|byte| byte == b'0') {
        return Err(de::Error::custom("network digest must be nonzero"));
    }
    Ok(digest)
}

fn bounded_vec<'de, D, T, const MAX: usize>(deserializer: D) -> Result<Vec<T>, D::Error>
where
    D: Deserializer<'de>,
    T: Deserialize<'de>,
{
    struct Visitor<T, const MAX: usize>(PhantomData<T>);
    impl<'de, T: Deserialize<'de>, const MAX: usize> de::Visitor<'de> for Visitor<T, MAX> {
        type Value = Vec<T>;
        fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            write!(f, "an array with at most {MAX} records")
        }
        fn visit_seq<A: de::SeqAccess<'de>>(self, mut seq: A) -> Result<Self::Value, A::Error> {
            let mut output = Vec::new();
            while let Some(item) = seq.next_element()? {
                if output.len() == MAX {
                    return Err(de::Error::custom("network array exceeds its record bound"));
                }
                output.push(item);
            }
            Ok(output)
        }
    }
    deserializer.deserialize_seq(Visitor::<T, MAX>(PhantomData))
}

fn roles<'de, D: Deserializer<'de>>(d: D) -> Result<Vec<NetworkRoleAssignment>, D::Error> {
    bounded_vec::<_, _, NETWORK_MAX_ROLES>(d)
}
fn parties<'de, D: Deserializer<'de>>(d: D) -> Result<Vec<NetworkPartyOffer>, D::Error> {
    bounded_vec::<_, _, NETWORK_MAX_PARTIES>(d)
}
fn capabilities<'de, D: Deserializer<'de>>(d: D) -> Result<Vec<String>, D::Error> {
    bounded_vec::<_, _, 4>(d)
}
fn allowed_models<'de, D: Deserializer<'de>>(d: D) -> Result<Vec<String>, D::Error> {
    bounded_vec::<_, _, NETWORK_MAX_ALLOWED_MODELS>(d)
}

fn requirements<'de, D: Deserializer<'de>>(d: D) -> Result<BTreeMap<String, u64>, D::Error> {
    struct Visitor;
    impl<'de> de::Visitor<'de> for Visitor {
        type Value = BTreeMap<String, u64>;
        fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
            write!(
                f,
                "a map of at most {NETWORK_MAX_ROLES} distinct role requirements"
            )
        }
        fn visit_map<A: de::MapAccess<'de>>(self, mut map: A) -> Result<Self::Value, A::Error> {
            let mut output = BTreeMap::new();
            while let Some((key, value)) = map.next_entry::<String, u64>()? {
                if output.len() == NETWORK_MAX_ROLES || output.insert(key, value).is_some() {
                    return Err(de::Error::custom(
                        "duplicate or excessive network requirements",
                    ));
                }
            }
            Ok(output)
        }
    }
    d.deserialize_map(Visitor)
}
