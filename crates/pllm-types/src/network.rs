/// Assignment-free requirements generated by complete native admission only.
/// Roles and separation pairs are identity-sorted and bounded by native topology.
#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
pub struct NetworkPlacementRequirements {
    pub schema: String,
    pub roles: Vec<NetworkRoleRequirement>,
    /// Operator ownership declarations; not proof of physical independence.
    pub separate_operators: Vec<[String; 2]>,
    /// One byte per owned tensor element, excluding copies/scales/peak memory.
    pub minimum_weight_bytes: BTreeMap<String, u64>,
    pub minimum_memory_bytes: BTreeMap<String, u64>,
    pub schedule_digest: Digest,
    pub model_plan_digest: Digest,
    pub composition_digest: Digest,
}

