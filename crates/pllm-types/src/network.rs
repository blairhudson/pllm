//! Strict bounded records for offline network placement admission.
//! Offers and operator IDs are declarations, not authentication or evidence of
//! physical independence. Resource requirements are caller-supplied estimates
//! constrained by native owned-tensor byte floors, not peak-RAM certificates.

use crate::Digest;
use serde::{de, Deserialize, Deserializer, Serialize};
use std::collections::BTreeMap;
use std::fmt;
use std::marker::PhantomData;

pub const NETWORK_PLACEMENT_SCHEMA: &str = "pllm.network_placement.v1";
pub const NETWORK_PLACEMENT_REQUIREMENTS_SCHEMA: &str = "pllm.network_placement_requirements.v1";
pub const NETWORK_PLACEMENT_DIGEST_DOMAIN: &str = "pllm.network_placement.validated.v1";
pub const NETWORK_MAX_DOCUMENT_BYTES: usize = 1024 * 1024;
pub const NETWORK_MAX_MODEL_PLAN_BYTES: usize = 16 * 1024 * 1024;
pub const NETWORK_MAX_ROLES: usize = 16;
pub const NETWORK_MAX_PARTIES: usize = 64;
pub const NETWORK_MAX_ALLOWED_MODELS: usize = 64;
pub const NETWORK_CAPABILITIES: &[&str] = &[
    "trusted_client",
    "masked_linear_provider",
    "trusted_preparation",
    "public_linear_provider",
];

/// Explicit experiment.v3 network intent. It has no local filesystem root.
/// The optional snapshot lock is an explicit null when planning from live offers.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct NetworkExperimentDeployment {
    pub network_id: String,
    #[serde(deserialize_with = "nonzero_digest")]
    pub network_spec_digest: Digest,
    #[serde(deserialize_with = "optional_nonzero_digest")]
    pub snapshot_digest: Option<Digest>,
}

fn optional_nonzero_digest<'de, D: Deserializer<'de>>(d: D) -> Result<Option<Digest>, D::Error> {
    let value = Option::<Digest>::deserialize(d)?;
    if value
        .as_ref()
        .is_some_and(|digest| digest.as_str().bytes().all(|byte| byte == b'0'))
    {
        return Err(de::Error::custom("network digest must be nonzero"));
    }
    Ok(value)
}

