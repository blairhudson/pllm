import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dataRoot = fileURLToPath(new URL('../data/research/', import.meta.url));
const outputRoot = fileURLToPath(new URL('../content/docs/research/papers/', import.meta.url));
const roadmapRoot = fileURLToPath(new URL('../content/docs/sdk/components/', import.meta.url));
const stubManifest = fileURLToPath(new URL('../../python/pllm/components/planned_methods.json', import.meta.url));
const generatedMarker = '{/* Generated by docs/scripts/generate-research-papers.mjs. */}';

function validate(registry, library, citationRegistry, summaries, libraryNotes, stubs) {
  if (registry.schema_version !== 'pllm.reproduction_portfolio.v2') {
    throw new Error(`Unsupported paper registry schema: ${registry.schema_version}`);
  }
  if (!Array.isArray(registry.papers) || registry.papers.length !== 24) {
    throw new Error('Paper registry must contain exactly 24 papers');
  }
  const ids = registry.papers.map((paper) => paper.id);
  const expected = Array.from({ length: 24 }, (_, index) => `R${String(index + 1).padStart(2, '0')}`);
  if (ids.join(',') !== expected.join(',')) throw new Error(`Expected ordered IDs ${expected.join(', ')}`);
  for (const paper of registry.papers) {
    if (!paper.primary_url.startsWith('https://')) throw new Error(`Invalid external source for ${paper.id}`);
    if (!paper.source_summary?.trim()) throw new Error(`Missing summary for ${paper.id}`);
  }
  const reviewedIds = registry.public_bibliography_ids;
  if (!Array.isArray(reviewedIds) || reviewedIds.some((id) => !ids.includes(id))) {
    throw new Error('Public bibliography IDs must identify registered papers');
  }
  if (Object.keys(summaries).length !== reviewedIds.length || reviewedIds.some((id) =>
    !summaries[id]?.overview?.trim() || !summaries[id]?.reading?.trim())) {
    throw new Error('Every reviewed paper needs an authored overview and PLLM reading note');
  }
  if (library.schema_version !== 'pllm.paper_library.v1' || library.papers.length !== 84) {
    throw new Error('The paper library must contain the 84 mapped sources and leads');
  }
  const mappedIds = library.papers.map((paper) => paper.id);
  const byRegistryId = new Map(registry.papers.map((paper) => [paper.id, paper]));
  const slugs = library.papers.map((paper) =>
    paper.registry_id ? byRegistryId.get(paper.registry_id)?.slug.replaceAll('_', '-') : paper.id);
  if (new Set(mappedIds).size !== 84 ||
    new Set(library.papers.map((paper) => paper.registry_id ?? paper.id)).size !== 84 ||
    new Set(slugs).size !== 84 || slugs.some((slug) => !slug) ||
    registry.papers.some((paper) =>
      !library.papers.some((mapped) => mapped.registry_id === paper.id))) {
    throw new Error('Each mapped paper must have a unique ID and retain all 24 locked records');
  }
  const missingNotes = library.papers.filter((paper) =>
    !summaries[paper.registry_id] && !libraryNotes[paper.id]).map((paper) => paper.id);
  const extraNotes = Object.keys(libraryNotes).filter((id) => !mappedIds.includes(id));
  const invalidSources = library.papers.filter((paper) => {
      const note = summaries[paper.registry_id] ?? libraryNotes[paper.id];
      return !note?.overview?.trim() || !note?.reading?.trim() ||
        !paper.source_url.startsWith('https://') ||
        !['available', 'pdf_unavailable', 'unverified_primary'].includes(paper.status) ||
        (paper.status === 'available' && !paper.sha256);
    }).map((paper) => paper.id);
  if (Object.keys(libraryNotes).length !== 84 - reviewedIds.length ||
    missingNotes.length || extraNotes.length || invalidSources.length) {
    throw new Error(`Invalid library notes/sources: missing ${missingNotes}, extra ${extraNotes}, invalid ${invalidSources}; ` +
      `${Object.keys(libraryNotes).length} notes for ${84 - reviewedIds.length} new entries`);
  }
  if (library.papers.filter((paper) => paper.status === 'unverified_primary')
    .some((paper) => paper.id !== 'ripple')) {
    throw new Error('New unverified leads require explicit review before publication');
  }
  if (stubs.schema !== 'pllm.component_plans.v1' || stubs.entries?.length !== 84 ||
    new Set(stubs.entries.map((stub) => stub.paper)).size !== 84 ||
    new Set(stubs.entries.map((stub) => `${stub.module}.${stub.name}`)).size !== 84 ||
    new Set(stubs.entries.map((stub) => `pllm/planned/${stub.paper}/v1`)).size !== 84) {
    throw new Error('The planned Python API must identify all 84 sources uniquely');
  }
  const papersById = new Map(library.papers.map((paper) => [paper.id, paper]));
  for (const stub of stubs.entries) {
    const paper = papersById.get(stub.paper);
    const slug = paper?.registry_id
      ? byRegistryId.get(paper.registry_id).slug.replaceAll('_', '-')
      : paper?.id;
    if (!paper || !stub.module.startsWith('pllm.') ||
      !/^[A-Z][A-Za-z0-9]*$/.test(stub.name) ||
      !['pending', 'implemented'].includes(stub.status ?? 'pending') ||
      !stub.gate?.trim() || stub.slug !== (slug === stub.paper ? undefined : slug) ||
      (paper.status === 'unverified_primary' && stub.kind !== 'unverified') ||
      (stub.kind === 'unverified' && paper.status !== 'unverified_primary')) {
      throw new Error(`Invalid planned Python API mapping: ${stub.paper}`);
    }
  }
  const citationIds = citationRegistry.citations.map((citation) => citation.paper_id);
  if (new Set(citationIds).size !== citationIds.length) {
    throw new Error('Each paper may have only one related-component citation');
  }
  for (const citation of citationRegistry.citations) {
    if (!reviewedIds.includes(citation.paper_id)) {
      throw new Error(`Component citation is not in the public bibliography: ${citation.paper_id}`);
    }
    if (!citation.summary?.trim() || !citation.components?.length) {
      throw new Error(`Incomplete component citation: ${citation.paper_id}`);
    }
  }
}

function originalLink(paper) {
  return paper.status === 'unverified_primary'
    ? '[Citing source: Curl](/research/papers/curl/)'
    : `[Original publication](${paper.source_url})`;
}

function provenance(paper) {
  if (paper.status === 'unverified_primary') {
    return 'Unverified source lead. No standalone primary publication is confirmed.';
  }
  if (paper.status === 'pdf_unavailable') {
    return 'The full text has not yet been reviewed for this source.';
  }
  return '';
}

function authorLine(paper) {
  return paper.authors?.length > 0 ? `${paper.authors.join(', ')} · ` : '';
}

function escapeFrontmatter(value) {
  return value.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
}

function escapeHtmlText(value) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function renderRelatedComponents(citation) {
  if (citation === undefined) return '';
  const links = citation.components
    .map((component) => `[${component.title}](${component.href})`)
    .join(', ');
  return `<Callout type="info" title="Related PLLM components">

${citation.summary}

Components: ${links}.

</Callout>

`;
}

function plannedApiLink(stub) {
  const moduleSlug = stub.module.slice(5).replaceAll('.', '-').replaceAll('_', '-');
  return `/sdk/reference/python/pllm/${moduleSlug}/#${stub.name.toLowerCase()}`;
}

function renderPlannedApi(stub) {
  const implemented = stub.status === 'implemented';
  const researchOnly = stub.kind !== undefined && stub.kind !== 'candidate'
    ? 'This is a research/assurance boundary, not a candidate for execution or optimisation. '
    : '';
  if (implemented) return `<Callout type="info" title="Related Python API">

[${stub.module}.${stub.name}](${plannedApiLink(stub)}) records the reviewed
implementation scope. Its public API and evidence define which experiments
may select it; the paper remains provenance, not an executable dependency.

</Callout>

`;
  return `<Callout type="warning" title="Planned Python API">

[${stub.module}.${stub.name}](${plannedApiLink(stub)}) documents this planned API. Construction
raises **NotYetImplementedError**; it is excluded from executable component discovery and search.
${researchOnly}Next gate: ${stub.gate}.

</Callout>

`;
}

function renderPaperPage(paper, citation, summary, stub) {
  const description = summary.overview;
  return `---
title: "${escapeFrontmatter(paper.title)}"
description: "${escapeFrontmatter(description)}"
---

${generatedMarker}

**${authorLine(paper)}${paper.year}**

${originalLink(paper)}

${provenance(paper)}

## Summary

${summary.overview}

## Reading this for PLLM

${summary.reading}

${renderRelatedComponents(citation)}
${renderPlannedApi(stub)}
`;
}

function renderRoadmap(papers, stubs) {
  const paperById = new Map(papers.map((paper) => [paper.id, paper]));
  const pendingCount = stubs.filter((stub) => stub.status !== 'implemented').length;
  const byModule = Map.groupBy(stubs, (stub) => stub.module);
  const groups = [...byModule].sort(([left], [right]) => left.localeCompare(right));
  const sections = groups.map(([module, items]) => `## \`${module}\`

| Python class | Research paper | API status | Next gate or scope |
| --- | --- | --- | --- |
${items.map((stub) => {
    const paper = paperById.get(stub.paper);
    const slug = stub.slug ?? stub.paper;
    return `| [\`${stub.name}\`](${plannedApiLink(stub)}) | [${paper.title}](/research/papers/${slug}/) | ${stub.status === 'implemented' ? 'Implemented' : 'Pending'} | ${stub.gate} |`;
  }).join('\n')}`).join('\n\n');
  return `---
title: "Research method roadmap"
description: "Paper-linked Python API symbols and their next implementation gates."
---

${generatedMarker}

All ${stubs.length} mapped sources have an importable Python symbol; ${pendingCount}
are still pending. Pending symbols
raise \`NotYetImplementedError\` on construction and are absent from executable
component discovery, Pipelines, and experiment search. Some sources describe
attacks, surveys, or unverified leads; those research-only symbols are not
inference methods. Existing related components have separate, scoped citations
on their paper pages and remain runnable only at their validated coverage.

This roadmap is generated from the packaged component plan. Each row
identifies the first missing gate; implementation also requires compatible
contracts, compiler and runtime coverage, checkpoint parity, and matched
evidence before search can include a method.

## Python SDK example

Inspect the [component plan API](/sdk/reference/python/pllm/components/)
without constructing a pending method:

API: [pllm.components](/sdk/reference/python/pllm/components/#objects-and-signatures)

\`\`\`python
from pllm.components import planned_components

plans = planned_components()
assert len(plans) == 84
assert all(plan.paper_route.startswith("/research/papers/") for plan in plans)
\`\`\`

${sections}
`;
}

function renderIndex(papers, summaries) {
  const years = [...new Set(papers.map((paper) => paper.year))];
  const sections = years.map((year) => `<section className="paper-timeline-year">

## ${year}

${papers.filter((paper) => paper.year === year).map((paper) => `<div className="paper-timeline-entry">

<div className="paper-timeline-title"><a href="/research/papers/${paper.slug}/">${escapeHtmlText(paper.title)}</a></div>

**${authorLine(paper)}${year}** · ${originalLink(paper)}

${provenance(paper)}

${summaries[paper.publicId].overview}

</div>`).join('\n\n')}

</section>`).join('\n\n');
  return `---
title: "Private Inference Papers"
description: "A newest-first timeline of private-inference research sources and leads."
---

${generatedMarker}

This timeline covers ${papers.length} mapped research sources and leads, newest
first. Publication years preserve the curated paper records where dates differ
between preprints and conference proceedings. The unverified lead is labelled
explicitly rather than presented as a separate published paper.
Where PLLM has a related implementation, the paper page names the exact component
and the component guide links back to its research source.

A related-component citation does not claim a complete reproduction. Read the
linked component status and evidence boundary before comparing results.

<div className="paper-timeline">

${sections}

</div>
`;
}

const registry = JSON.parse(fs.readFileSync(path.join(dataRoot, 'papers.json'), 'utf8'));
const library = JSON.parse(fs.readFileSync(path.join(dataRoot, 'paper-library.json'), 'utf8'));
const citationRegistry = JSON.parse(fs.readFileSync(path.join(dataRoot, 'component-citations.json'), 'utf8'));
const summaries = JSON.parse(fs.readFileSync(path.join(dataRoot, 'public-summaries.json'), 'utf8'));
const libraryNotes = JSON.parse(fs.readFileSync(path.join(dataRoot, 'paper-library-notes.json'), 'utf8'));
const stubs = JSON.parse(fs.readFileSync(stubManifest, 'utf8'));
validate(registry, library, citationRegistry, summaries, libraryNotes, stubs);
fs.mkdirSync(outputRoot, { recursive: true });

const citationByPaperId = new Map(citationRegistry.citations.map((citation) => [citation.paper_id, citation]));
const publicPapers = library.papers.map((paper) => ({
  ...paper,
  authors: paper.authors?.length > 0 ? paper.authors
    : registry.papers.find((registered) => registered.id === paper.registry_id)?.authors ?? [],
  slug: paper.registry_id
    ? registry.papers.find((registered) => registered.id === paper.registry_id).slug.replaceAll('_', '-')
    : paper.id,
  publicId: paper.registry_id ?? paper.id,
}))
  .sort((left, right) => right.year - left.year || left.title.localeCompare(right.title));
const authoredSummary = (paper) => summaries[paper.registry_id] ?? libraryNotes[paper.id];
const stubByPaper = new Map(stubs.entries.map((stub) => [stub.paper, stub]));
const years = [...new Set(publicPapers.map((paper) => paper.year))];
const generated = new Map([
  ['index.mdx', renderIndex(publicPapers, Object.fromEntries(publicPapers.map((paper) =>
    [paper.publicId, authoredSummary(paper)])))],
  ...publicPapers.map((paper) => [
    `${paper.slug}.mdx`,
    renderPaperPage(paper, citationByPaperId.get(paper.registry_id), authoredSummary(paper), stubByPaper.get(paper.id)),
  ]),
  ['meta.json', `${JSON.stringify({
    title: 'Private Inference Papers',
    root: true,
    pages: [
      'index',
      ...years.flatMap((year) => [
        `--- ${year} ---`,
        ...publicPapers.filter((paper) => paper.year === year).map((paper) => paper.slug),
      ]),
    ],
  }, null, 2)}\n`],
]);

for (const entry of fs.readdirSync(outputRoot, { withFileTypes: true })) {
  if (entry.isFile() && /\.(?:mdx|json)$/.test(entry.name) && !generated.has(entry.name)) {
    fs.rmSync(path.join(outputRoot, entry.name));
  }
}
for (const [filename, content] of generated) {
  const target = path.join(outputRoot, filename);
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) fs.writeFileSync(target, content);
}
const roadmap = path.join(roadmapRoot, 'research-method-roadmap.mdx');
const roadmapContent = renderRoadmap(publicPapers, stubs.entries);
if (!fs.existsSync(roadmap) || fs.readFileSync(roadmap, 'utf8') !== roadmapContent) {
  fs.writeFileSync(roadmap, roadmapContent);
}

console.log(`Generated a newest-first timeline and ${publicPapers.length} research source/lead pages.`);
