import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const docsRoot = fileURLToPath(new URL('../content/docs/', import.meta.url));
const outputPath = fileURLToPath(new URL('./discovered-docs.mjs', import.meta.url));

function walkMdx(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const candidate = path.join(directory, entry.name);
    return entry.isDirectory() ? walkMdx(candidate) : candidate.endsWith('.mdx') ? [candidate] : [];
  });
}

const discoveredDocs = walkMdx(docsRoot)
  .map((file) => path.relative(docsRoot, file).replaceAll(path.sep, '/').replace(/\.mdx$/, ''))
  .sort();
const output = `// Generated by scripts/discover-pages.mjs; do not edit.\nexport const discoveredDocs = ${JSON.stringify(discoveredDocs, null, 2)};\n`;
fs.writeFileSync(outputPath, output);

const versionPath = fileURLToPath(new URL('../../python/pllm/_version.py', import.meta.url));
const packageVersion = /__version__\s*=\s*"([^"]+)"/.exec(fs.readFileSync(versionPath, 'utf8'))[1];
const versionOutputPath = fileURLToPath(new URL('./package-version.mjs', import.meta.url));
fs.writeFileSync(
  versionOutputPath,
  `// Generated by scripts/discover-pages.mjs; do not edit.\nexport const packageVersion = ${JSON.stringify(packageVersion)};\n`,
);
